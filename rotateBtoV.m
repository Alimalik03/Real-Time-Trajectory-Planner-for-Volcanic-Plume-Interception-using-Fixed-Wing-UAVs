function XYZ = rotateBtoV(XYZ,phi,theta,psi)
%% function to rotate from body frame to inertial(vehicle) frame. %%

    R_roll = [...
            1, 0, 0;...
            0, cos(phi), sin(phi);...
            0, -sin(phi), cos(phi)]; % direction changed as it was rolling left positive
    
    R_pitch = [...
            cos(theta), 0, -sin(theta);...
            0, 1, 0;...
            sin(theta), 0, cos(theta)]; % direction changed as it was pitching down positive
        
    R_yaw = [...
            cos(psi), sin(psi), 0;...
            -sin(psi), cos(psi), 0; ...
            0,0,1];

R = R_roll*(R_pitch*R_yaw); % Rotation Matrix

%to get R from body to inertial, we transpose the matrix
R = R';

% to express in body frame
XYZ = R*XYZ;