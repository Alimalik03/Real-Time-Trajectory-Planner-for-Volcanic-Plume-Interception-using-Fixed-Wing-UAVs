function XYZ = rotate_VtoB(XYZ,phi,theta,psi)
    % define rotation matrix as derived in Chpt. 2, using Euler angles phi
    % (roll), theta (pitch), psi (yaw)
    R_roll = [...
            1, 0, 0;...
            0, cos(phi), sin(phi);...
            0, -sin(phi), cos(phi)]; % direction changed as it was rolling left positive
    
    R_pitch = [...
            cos(theta), 0, -sin(theta);...
            0, 1, 0;...
            sin(theta), 0, cos(theta)]; % direction changed as it was pitching down positive
        
    R_yaw = [...
            cos(psi), sin(psi), 0;...
            -sin(psi), cos(psi), 0; ...
            0,0,1];
        
    R = R_roll*(R_pitch*R_yaw); % The order of the multiplication here is important
    
    % Rotate the vertices passed in the matric XYZ
    XYZ = R*XYZ;
    
    
    